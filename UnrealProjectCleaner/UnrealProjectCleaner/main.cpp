void CleanSelected(std::vector<GroupInfo>& groups, const fs::path& startPath)
{
    // Plugin group names — used to protect their subdirs inside the project root Intermediate
    std::vector<std::string> pluginNames;
    for (size_t i = 1; i < groups.size(); ++i)
        pluginNames.push_back(groups[i].name);

    std::cout << "\n" << COL_YELLOW << "Cleaning..." << COL_RESET << "\n";
    int cleaned = 0;
    for (size_t i = 0; i < groups.size(); ++i)
    {
        auto& g = groups[i];
        if (!g.selected) continue;
        if (i == 0)
        {
            // Project root: protect plugin and shared-build artefacts so UBT doesn't rebuild them.
            //
            // x64/ layout inside Intermediate/Build/Win64/x64/:
            //   <Target>/<Config>/Core/    ← SharedPCH for engine modules  → KEEP
            //   <Target>/<Config>/Engine/  ← SharedPCH for engine modules  → KEEP
            //   <Target>/<Config>/<Plugin>/← plugin SharedPCH              → KEEP
            //   <Target>/<Config>/<Mod>/   ← project module .obj files     → DELETE
            //
            // Strategy: skip x64/ in the main CleanPath (preserves all SharedPCH), then
            // specifically delete only the project module subdirs under x64/.
            std::vector<std::string> projectSkipDirs = pluginNames;
            projectSkipDirs.push_back("x64");
            CleanPath(g.binariesPath,     pluginNames, pluginNames);
            CleanPath(g.intermediatePath, projectSkipDirs);

            // Delete project module .obj files under x64/ without touching SharedPCH dirs
            auto moduleNames = GetProjectModuleNames(startPath);
            fs::path x64Base = g.intermediatePath / "Build" / "Win64" / "x64";
            CleanProjectModuleDirsUnderX64(x64Base, moduleNames);
        }
        else
        {
            CleanPath(g.binariesPath);
            CleanPath(g.intermediatePath);
        }
        ++cleaned;
    }
    DeleteSlnFiles(startPath);
    std::cout << COL_GREEN << "  " << cleaned << " entry(s) cleaned." << COL_RESET << "\n";
}

void RunGenerateProjectFiles(const fs::path& startPath)
{
    fs::path uproject = FindUprojectFile(startPath);
    if (!uproject.empty()) GenerateProjectFiles(uproject);
}

