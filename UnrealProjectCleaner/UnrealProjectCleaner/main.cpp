// Returns module names found directly inside <projectRoot>/Source/ — each subdirectory that
// contains a *.Build.cs file is a module.  This is used to identify which x64/ subdirectories
// belong to the project (vs engine or plugin modules that share the same x64/ folder).
std::vector<std::string> GetProjectModuleNames(const fs::path& projectRoot)
{
    std::vector<std::string> modules;
    fs::path sourceDir = projectRoot / "Source";
    if (!fs::exists(sourceDir)) return modules;
    try
    {
        for (auto& entry : fs::directory_iterator(sourceDir, fs::directory_options::skip_permission_denied))
        {
            if (!entry.is_directory()) continue;
            // A directory is a module if it contains a <Name>.Build.cs file
            for (auto& f : fs::directory_iterator(entry.path(), fs::directory_options::skip_permission_denied))
            {
                if (!f.is_regular_file()) continue;
                // Extension must be ".cs" and the stem must end in ".Build"
                std::string ext  = f.path().extension().string();
                std::string stem = f.path().stem().string();           // e.g. "Calypso.Build"
                std::string stemExt = fs::path(stem).extension().string(); // ".Build"
                if (_stricmp(ext.c_str(), ".cs") == 0 &&
                    _stricmp(stemExt.c_str(), ".Build") == 0)
                { modules.push_back(entry.path().filename().string()); break; }
            }
        }
    }
    catch (...) {}
    return modules;
}

// Clean only the project module dirs inside x64/<Target>/<Config>/<ModuleName>/.
// This deletes the project module's .obj files without touching SharedPCH dirs
// (Core, Engine, etc.) that are also stored under x64/.
void CleanProjectModuleDirsUnderX64(const fs::path& x64Base,
                                     const std::vector<std::string>& moduleNames)
{
    if (!fs::exists(x64Base) || moduleNames.empty()) return;
    try
    {
        for (auto& targetEntry : fs::directory_iterator(x64Base, fs::directory_options::skip_permission_denied))
        {
            if (!targetEntry.is_directory()) continue;
            for (auto& configEntry : fs::directory_iterator(targetEntry.path(), fs::directory_options::skip_permission_denied))
            {
                if (!configEntry.is_directory()) continue;
                for (const auto& mod : moduleNames)
                    CleanPath(configEntry.path() / mod);
            }
        }
    }
    catch (...) {}
}

// Count deletable files inside the project module dirs under x64/ (mirrors CleanProjectModuleDirsUnderX64).
int CountProjectModuleFilesUnderX64(const fs::path& x64Base,
                                     const std::vector<std::string>& moduleNames)
{
    int total = 0;
    if (!fs::exists(x64Base) || moduleNames.empty()) return total;
    try
    {
        for (auto& targetEntry : fs::directory_iterator(x64Base, fs::directory_options::skip_permission_denied))
        {
            if (!targetEntry.is_directory()) continue;
            for (auto& configEntry : fs::directory_iterator(targetEntry.path(), fs::directory_options::skip_permission_denied))
            {
                if (!configEntry.is_directory()) continue;
                for (const auto& mod : moduleNames)
                {
                    fs::path modDir = configEntry.path() / mod;
                    if (fs::exists(modDir))
                        total += CountDeletableFiles(modDir.wstring(), false);
                }
            }
        }
    }
    catch (...) {}
    return total;
}

// Build a GroupInfo for a given owner directory (project root or plugin dir).
// isProjectRoot=true  → skips "x64/" when counting Intermediate files (matches CleanSelected logic)
GroupInfo BuildGroup(const std::string& name, const fs::path& ownerDir, bool isProjectRoot = false)
{
    GroupInfo g;
    g.name = name;

    fs::path bin = ownerDir / "Binaries";
    fs::path mid = ownerDir / "Intermediate";

    if (fs::exists(bin) && fs::is_directory(bin))   g.binariesPath     = bin;
    if (fs::exists(mid) && fs::is_directory(mid))   g.intermediatePath = mid;

    // For the project root:
    //   - x64/ is skipped in the main Intermediate count because it contains SharedPCH files
    //     used by ALL modules (engine, plugins).  Deleting them causes full rebuild.
    //   - We separately count only the project module dirs under x64/ (those will be cleaned).
    std::vector<std::string> intermediateSkip;
    if (isProjectRoot) intermediateSkip.push_back("x64");

    // Count only deletable files, in parallel
    std::future<int> fb, fm;
    if (!g.binariesPath.empty())
        fb = std::async(std::launch::async, CountDeletableFiles,
                        g.binariesPath.wstring(), true, std::vector<std::string>{});
    if (!g.intermediatePath.empty())
        fm = std::async(std::launch::async, CountDeletableFiles,
                        g.intermediatePath.wstring(), false, intermediateSkip);

    if (!g.binariesPath.empty())     g.binariesCount     = fb.get();
    if (!g.intermediatePath.empty()) g.intermediateCount = fm.get();

    // Project root: add count for project module obj files under x64/
    if (isProjectRoot && !g.intermediatePath.empty())
    {
        auto moduleNames = GetProjectModuleNames(ownerDir);
        fs::path x64Base = g.intermediatePath / "Build" / "Win64" / "x64";
        g.intermediateCount += CountProjectModuleFilesUnderX64(x64Base, moduleNames);
    }

    return g;
}

// Recursively find all directories under pluginsDir that have
// a direct Binaries or Intermediate child (these are plugin owners)
std::vector<fs::path> FindPluginOwners(const fs::path& pluginsDir)
{
    std::vector<fs::path> owners;
    if (!fs::exists(pluginsDir)) return owners;
    try
    {
        auto it = fs::recursive_directory_iterator(pluginsDir, fs::directory_options::skip_permission_denied);
        for (auto& e : it)
        {
            if (!e.is_directory()) continue;
            std::string name = e.path().filename().string();
            if (_stricmp(name.c_str(), "Binaries") == 0 ||
                _stricmp(name.c_str(), "Intermediate") == 0)
            {
                owners.push_back(e.path().parent_path());
                it.disable_recursion_pending();
            }
        }
    }
    catch (...) {}

    // Remove duplicates (a dir can have both Binaries and Intermediate)
    std::sort(owners.begin(), owners.end());
    owners.erase(std::unique(owners.begin(), owners.end()), owners.end());
    return owners;
}

std::vector<GroupInfo> FindTargetFolders(const fs::path& startPath)
{
    std::vector<GroupInfo> result;

    // 1. Project root (isProjectRoot=true so the count mirrors what CleanSelected will actually delete)
    std::string projectName = GetProjectName(startPath);
    auto rootGroup = BuildGroup(projectName, startPath, /*isProjectRoot=*/true);
    if (!rootGroup.binariesPath.empty() || !rootGroup.intermediatePath.empty())
        result.push_back(std::move(rootGroup));

    // 2. All plugin owners (handles nested plugin structures)
    auto pluginOwners = FindPluginOwners(startPath / "Plugins");

    std::vector<std::future<GroupInfo>> futures;
    futures.reserve(pluginOwners.size());
    for (auto& dir : pluginOwners)
        futures.push_back(std::async(std::launch::async, BuildGroup,
                                     dir.filename().string(), dir, /*isProjectRoot=*/false));

    for (auto& f : futures)
    {
        auto g = f.get();
        if (!g.binariesPath.empty() || !g.intermediatePath.empty())
            result.push_back(std::move(g));
    }

    return result;
}

